class FrontDoorPlugin:
    """Generates Azure Front Door Bicep module for global load balancing."""

    meta = ResourcePluginMeta(
        resource_type="front-door",
        bicep_prefix="afd",
        description="Azure Front Door Standard/Premium with WAF policy",
        azure_provider="Microsoft.Cdn",
    )

    def applies_to(self, spec: IntentSpec) -> bool:
        keywords = {"front door", "cdn", "global", "multi-region", "edge", "load balancing"}
        raw = spec.raw_intent.lower()
        return (
            any(kw in raw for kw in keywords)
            or spec.security.enable_waf
        )

    def generate(self, spec: IntentSpec, **kwargs) -> dict[str, str]:
        name = f"afd-{spec.project_name}-{spec.environment}"
        tags = _common_tags(spec)
        return {
            "infra/bicep/modules/front-door.bicep": f"""\
// Azure Front Door Standard with WAF Policy
// Generated by: resource_plugin / FrontDoorPlugin

@description('Front Door profile for global load balancing and WAF')
param location string = 'global'
param workloadName string = '{spec.project_name}'
param environmentName string = '{spec.environment}'
param backendAddress string

var profileName = '{name}'
var wafPolicyName = 'wafpol${{replace(workloadName, '-', '')}}${{environmentName}}'

resource frontDoorProfile 'Microsoft.Cdn/profiles@2023-05-01' = {{
  name: profileName
  location: location
  tags: {tags}
  sku: {{
    name: 'Standard_AzureFrontDoor'
  }}
}}

resource wafPolicy 'Microsoft.Network/FrontDoorWebApplicationFirewallPolicies@2022-05-01' = {{
  name: wafPolicyName
  location: location
  tags: {tags}
  properties: {{
    policySettings: {{
      enabledState: 'Enabled'
      mode: 'Prevention'
      requestBodyCheck: 'Enabled'
    }}
    managedRules: {{
      managedRuleSets: [
        {{
          ruleSetType: 'Microsoft_DefaultRuleSet'
          ruleSetVersion: '2.1'
          ruleSetAction: 'Block'
        }}
        {{
          ruleSetType: 'Microsoft_BotManagerRuleSet'
          ruleSetVersion: '1.0'
          ruleSetAction: 'Block'
        }}
      ]
    }}
  }}
}}

resource endpoint 'Microsoft.Cdn/profiles/afdEndpoints@2023-05-01' = {{
  parent: frontDoorProfile
  name: '${{workloadName}}-endpoint'
  location: location
  properties: {{
    enabledState: 'Enabled'
  }}
}}

resource originGroup 'Microsoft.Cdn/profiles/originGroups@2023-05-01' = {{
  parent: frontDoorProfile
  name: 'default-origin-group'
  properties: {{
    loadBalancingSettings: {{
      sampleSize: 4
      successfulSamplesRequired: 3
      additionalLatencyInMilliseconds: 50
    }}
    healthProbeSettings: {{
      probePath: '/health'
      probeRequestType: 'HEAD'
      probeProtocol: 'Https'
      probeIntervalInSeconds: 30
    }}
  }}
}}

resource origin 'Microsoft.Cdn/profiles/originGroups/origins@2023-05-01' = {{
  parent: originGroup
  name: 'backend-origin'
  properties: {{
    hostName: backendAddress
    httpPort: 80
    httpsPort: 443
    originHostHeader: backendAddress
    priority: 1
    weight: 1000
    enforceCertificateNameCheck: true
  }}
}}

output frontDoorId string = frontDoorProfile.id
output endpointHostName string = endpoint.properties.hostName
""",
        }


def _common_tags(spec: IntentSpec) -> str:
    """Generate Bicep tags object literal."""
    return f"""{{
    project: '{spec.project_name}'
    environment: '{spec.environment}'
    managedBy: 'bicep'
    dataSensitivity: '{spec.security.data_classification}'
  }}"""
