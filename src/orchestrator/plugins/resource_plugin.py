"""Resource Plugins -- custom Azure resource Bicep modules.

Each plugin generates Bicep modules for Azure resources not included
in the core BicepGenerator (Service Bus, Event Grid, Front Door, etc.).
Plugins use ``applies_to(spec)`` to decide whether to activate.
"""

from __future__ import annotations

from dataclasses import dataclass

from src.orchestrator.intent_schema import IntentSpec
from src.orchestrator.logging import get_logger

logger = get_logger(__name__)


@dataclass(frozen=True)
class ResourcePluginMeta:
    """Metadata describing a resource plugin's capabilities."""

    resource_type: str
    bicep_prefix: str
    description: str
    azure_provider: str


class ServiceBusPlugin:
    """Generates Azure Service Bus Bicep module for event-driven workloads."""

    meta = ResourcePluginMeta(
        resource_type="service-bus",
        bicep_prefix="sb",
        description="Azure Service Bus namespace with queues and topics",
        azure_provider="Microsoft.ServiceBus",
    )

    def applies_to(self, spec: IntentSpec) -> bool:
        keywords = {"event-driven", "message", "queue", "topic", "pub/sub", "service bus", "async", "decouple"}
        raw = spec.raw_intent.lower()
        return any(kw in raw for kw in keywords)

    def generate(self, spec: IntentSpec, **kwargs) -> dict[str, str]:
        name = f"sb-{spec.project_name}-{spec.environment}"
        tags = _common_tags(spec)
        return {
            "infra/bicep/modules/service-bus.bicep": f"""\
// Azure Service Bus Namespace
// Generated by: resource_plugin / ServiceBusPlugin

@description('Service Bus namespace for async messaging')
param location string = resourceGroup().location
param environmentName string = '{spec.environment}'
param workloadName string = '{spec.project_name}'
param managedIdentityPrincipalId string

var sbName = '{name}'

resource serviceBusNamespace 'Microsoft.ServiceBus/namespaces@2022-10-01-preview' = {{
  name: sbName
  location: location
  sku: {{
    name: 'Standard'
    tier: 'Standard'
  }}
  tags: {tags}
  properties: {{
    minimumTlsVersion: '1.2'
    publicNetworkAccess: 'Enabled'
    disableLocalAuth: true
  }}
}}

// Default queue
resource defaultQueue 'Microsoft.ServiceBus/namespaces/queues@2022-10-01-preview' = {{
  parent: serviceBusNamespace
  name: '${{workloadName}}-events'
  properties: {{
    maxDeliveryCount: 10
    lockDuration: 'PT1M'
    defaultMessageTimeToLive: 'P14D'
    deadLetteringOnMessageExpiration: true
  }}
}}

// Default topic
resource defaultTopic 'Microsoft.ServiceBus/namespaces/topics@2022-10-01-preview' = {{
  parent: serviceBusNamespace
  name: '${{workloadName}}-notifications'
  properties: {{
    defaultMessageTimeToLive: 'P14D'
    maxSizeInMegabytes: 1024
  }}
}}

// RBAC: Azure Service Bus Data Sender for managed identity
resource senderRole 'Microsoft.Authorization/roleAssignments@2022-04-01' = {{
  name: guid(serviceBusNamespace.id, managedIdentityPrincipalId, '69a216fc-b8fb-44d8-bc22-1f3c2cd27a39')
  scope: serviceBusNamespace
  properties: {{
    roleDefinitionId: subscriptionResourceId('Microsoft.Authorization/roleDefinitions', '69a216fc-b8fb-44d8-bc22-1f3c2cd27a39')
    principalId: managedIdentityPrincipalId
    principalType: 'ServicePrincipal'
  }}
}}

// RBAC: Azure Service Bus Data Receiver
resource receiverRole 'Microsoft.Authorization/roleAssignments@2022-04-01' = {{
  name: guid(serviceBusNamespace.id, managedIdentityPrincipalId, '4f6d3b9b-027b-4f4c-9142-0e5a2a2247e0')
  scope: serviceBusNamespace
  properties: {{
    roleDefinitionId: subscriptionResourceId('Microsoft.Authorization/roleDefinitions', '4f6d3b9b-027b-4f4c-9142-0e5a2a2247e0')
    principalId: managedIdentityPrincipalId
    principalType: 'ServicePrincipal'
  }}
}}

output serviceBusId string = serviceBusNamespace.id
output serviceBusEndpoint string = serviceBusNamespace.properties.serviceBusEndpoint
""",
        }


